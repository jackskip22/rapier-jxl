export function listingWords() {
  const code = (language, body) => '```' + language + '\n' + body + '\n```';
  const description = [WORDS.titleInfo, WORDS.listingEncoder, WORDS.originalsInfo, code('sh', WORDS.setupCommand),
    'Works with ' + WORDS.faqStorageAnswer].join('\n\n');
  const installation = [WORDS.setupIntro, code('sh', WORDS.setupCommand),
    'Or tell your coding agent:', '"' + WORDS.setupAgent + '"',
    'Or install `rapier-jxl`, then in `astro.config.mjs` wrap your EmDash setup:',
    code('js', "import {jxl} from 'rapier-jxl/emdash';\n\njxl(emdash, {database, storage});")].join('\n\n');
  const faq = [[WORDS.faqOriginalQuestion, WORDS.faqOriginalAnswer], [WORDS.faqBrowsersQuestion, WORDS.faqBrowsersAnswer],
    [WORDS.faqRemovalQuestion, WORDS.faqRemovalAnswer], [WORDS.faqStorageQuestion, WORDS.faqStorageAnswer]]
    .map(([question, answer]) => `- **${question}** ${answer}`).join('\n');
  const sections = '## Description\n\n' + description + '\n\n## Installation\n\n' + installation + '\n\n## FAQ\n\n' + faq + '\n';
  return {description: description + '\n', installation: installation + '\n', faq: faq + '\n',
    readme: '# ' + WORDS.name + '\n\n' + WORDS.listing + '\n\n' + sections,
    submission: '# ' + WORDS.name + ': EmDash listing\n\n' +
      'For emdash.directory (the plug-in) and the official EmDash registry (the setup guide). Same words in both.\n\n' +
      '**Name:** ' + WORDS.name + '\n\n**Registry name:** @rapier.website/jxl\n\n**One line:** ' + WORDS.listing + '\n\n' + sections};
}

export function words(template, values = {}) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key]));
}

